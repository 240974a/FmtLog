// Уведомления по SNMP.
//
//     #include <FmtLog.h>
//     #include <FmtSnmp.h>
//
//     void setup() {
//         WiFi.begin(ssid, pass);
//         snmp::begin(IPAddress(192, 168, 1, 10));   // куда слать
//         log::addSink(snmp::sink);
//     }
//
//     void loop() {
//         snmp::handle();            // звать в каждом проходе цикла
//     }
//
// В журнал приёмник не годится: это не строка в ленте, а событие,
// которое ждёт дежурный. Поэтому уходит не всё подряд, а только err и выше -
// порог меняется через setLevel().
//
// Отправляется trap SNMPv2c на порт 162. Сообщение кладётся в переменную
// внутри trap, а рядом идут номер уровня и имя источника - по ним фильтруют
// на стороне приёмника, не разбирая текст.
//
// Пакет собирается прямо здесь, без библиотеки SNMP: trap - единственное, что
// нужно журналу, а его кодирование занимает меньше места, чем любая готовая
// реализация вместе с разбором запросов, которые плате слушать незачем.
//
// Заголовок отдельный: приложению без SNMP он не достанется даже мёртвым
// кодом.
#pragma once

#if !defined(ESP8266) && !defined(ESP32)
#error "FmtSnmp.h needs WiFi: it works on ESP8266 and ESP32 only"
#endif

#include <IPAddress.h>

#include "Log.h"

namespace fmtlog {
    namespace snmp {

        // Приёмник журнала - его и передавать в log::addSink.
        void sink(const Record& record);

        // Куда и от чьего имени слать. community - пароль в открытую, каким
        // он в SNMPv2c и задуман; порт 162 стандартный для trap.
        void begin(IPAddress receiver, const char* community = "public",
                   uint16_t port = 162);

        // Отправляет накопленное. Звать в каждом проходе loop().
        //
        // Сам sink() ничего не шлёт: он вызывается изнутри log::err(), а
        // отправка по сети заняла бы там миллисекунды.
        void handle();

        // Закрывает сокет.
        void end();

        // С какого уровня слать. По умолчанию err: ниже - обычные рабочие
        // сообщения, дёргать ими дежурного незачем.
        void setLevel(Level level);

        // Корень OID для переменных внутри trap. По умолчанию ветка
        // enterprises.experimental (1.3.6.1.3.1) - она свободна для проб.
        // Своим устройствам укажите свою: у организации она уже есть.
        //
        //     snmp::setEnterpriseOid("1.3.6.1.4.1.12345");
        void setEnterpriseOid(const char* dotted);

        // Сколько событий не поместилось в очередь и потеряно. Растёт, если
        // сеть недоступна дольше, чем вмещает очередь.
        uint16_t lost();

        // Сколько событий ждёт отправки.
        uint8_t pending();

    } // namespace snmp
} // namespace fmtlog
