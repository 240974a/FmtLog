// Журнал по сети: telnet-приёмник с историей.
//
//     #include <FmtLog.h>
//     #include <FmtTelnet.h>
//
//     void setup() {
//         WiFi.begin(ssid, pass);
//         telnet::begin();
//         log::addSink(telnet::sink);
//     }
//
//     void loop() {
//         telnet::handle();     // звать в каждом проходе цикла
//     }
//
// Подключившийся видит не только новые сообщения, но и накопленную историю -
// столько, сколько её поместилось. У каждого соединения своё место в ней,
// поэтому второй и третий клиент получают ту же глубину, что и первый:
// чтение ничего не стирает.
//
// Заголовок отдельный: приложению без сети он не достанется даже мёртвым
// кодом.
#pragma once

#include "FmtHistory.h"
#include "Log.h"

namespace fmtlog {
    namespace telnet {

        // Приёмник журнала - его и передавать в log::addSink.
        void sink(const Record& record);

        // Открывает порт. Звать после подъёма сети.
        void begin(uint16_t port = 23);

        // Принимает подключения и досылает клиентам накопленное.
        // Звать в каждом проходе loop().
        void handle();

        // Закрывает порт и все соединения.
        void end();

        // Сколько клиентов сейчас подключено.
        uint8_t clientCount();

        // Что видит подключившийся: всю сохранённую историю или только новые
        // сообщения. По умолчанию историю - ради неё всё и затевалось.
        void setSendHistory(bool send);

    } // namespace telnet
} // namespace fmtlog
