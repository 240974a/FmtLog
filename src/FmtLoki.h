// Журнал в Loki - хранилище логов, которое читают рядом с Prometheus.
//
//     #include <FmtLog.h>
//     #include <FmtLoki.h>
//
//     void setup() {
//         WiFi.begin(ssid, pass);
//         loki::begin("192.168.1.10", 3100);
//         loki::addLabel("job", "boiler");
//         log::addSink(loki::sink);
//     }
//
//     void loop() {
//         loki::handle();            // звать в каждом проходе цикла
//     }
//
// Строки уходят пачками, а не по одной: у Loki на каждый запрос свои
// накладные - и сетевые, и на его стороне. Пачка отправляется, когда набралось
// достаточно строк или прошло время, - что случится раньше.
//
// Метки - то, по чему в Loki потом ищут. Уровень и источник библиотека
// подставляет сама, а job, instance и прочее задаёт приложение через
// addLabel(). Меток должно быть немного: в Loki каждое их сочетание заводит
// отдельный поток.
//
// Время берётся из журнала: если приложение вызывало log::setTime(), строки
// лягут по настоящему времени, иначе - по времени доставки, отмеченному самим
// Loki.
//
// Заголовок отдельный: приложению без Loki он не достанется даже мёртвым
// кодом.
#pragma once

#if !defined(ESP8266) && !defined(ESP32)
#error "FmtLoki.h needs WiFi: it works on ESP8266 and ESP32 only"
#endif

#include "Log.h"

namespace fmtlog {
    namespace loki {

        // Приёмник журнала - его и передавать в log::addSink.
        void sink(const Record& record);

        // Куда слать. path менять нужно редко - разве что перед Loki стоит
        // обратный прокси со своим адресом.
        void begin(const char* host, uint16_t port = 3100,
                   const char* path = "/loki/api/v1/push");

        // Отправляет накопленное, когда пачка набралась или вышло время.
        // Звать в каждом проходе loop().
        void handle();

        // Досылает накопленное немедленно, не дожидаясь пачки. Пригодится
        // перед перезагрузкой или сном - иначе последние строки пропадут.
        void flush();

        // Закрывает соединение. Накопленное не отправляется - для этого
        // flush().
        void end();

        // Своя метка, общая для всех строк: job, instance, место установки.
        // Повторный вызов с тем же именем меняет значение.
        //
        // Возвращает false, если места под метки больше нет.
        bool addLabel(const char* name, const char* value);

        // С какого уровня слать. По умолчанию идёт всё, что дошло до приёмника.
        void setLevel(Level level);

        // Сколько строк потеряно: буфер переполнился, пока Loki был
        // недоступен.
        uint16_t lost();

        // Сколько строк ждёт отправки.
        uint16_t pending();

        // Отправлена ли последняя пачка. Пригодится, чтобы показать связь с
        // Loki на своей странице состояния.
        bool connected();

    } // namespace loki
} // namespace fmtlog
